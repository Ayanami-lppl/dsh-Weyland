def read(path):
    with io.open(path, encoding="utf-8") as fh:
        return fh.read()


def extract_markup(html):
    return html[html.index("<body>") + len("<body>"):html.index("<script")].strip()


def scoped(css):
    """Turn the page stylesheet into one that is valid inside a shadow root."""
    css = css.replace(":root {", ":host {", 1)
    css, n1 = re.subn(r"html,\s*body\s*\{[^}]*\}", HOST_RULE, css, count=1)
    css, n2 = re.subn(r"\nbody\s*\{", "\n:host {", css, count=1)
    if n1 != 1 or n2 != 1:
        raise SystemExit("splash.css head is not shaped as expected (html,body=%d body=%d)"
                         % (n1, n2))
    return css


def render(alternate):
    markup = extract_markup(read(os.path.join(SPLASH, "index.html")))
    css = scoped(read(os.path.join(SPLASH, "splash.css")))

    if 'class="screen"' not in markup or "fx-poweroff" not in markup:
        raise SystemExit("markup extraction looks wrong -- check splash/index.html")

    source = read(os.path.join(SPLASH, "splash.js"))
    found = re.search(r"Math\.max\(\s*\d+\s*,\s*Number\([^)]*\)\s*\|\|\s*(\d+)\s*\)", source)
    duration = int(found.group(1)) if found else 8000

    return TEMPLATE % {
        "markup": json.dumps(markup),
        "css": json.dumps(css, ensure_ascii=False),
        "duration": duration,
        "alternate": "true" if alternate else "false",
    }


def main():
    alternate = "--alternate" in sys.argv
    out = render(alternate)

    print("source  :", SPLASH)
    print("mode    :", "alternate (shares the machine)" if alternate else "always play")
    print("result  : %d bytes" % len(out))

    if "--check" in sys.argv:
        print("(check only, nothing written)")
        return
    with io.open(TARGET, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(out)
    print("written :", TARGET)


if __name__ == "__main__":
    main()
